// Owner-created pages and posts → real website source (used by live-source.mjs generate, build-live.mjs
// and source-diff.mjs). Deterministic, offline, zero model calls.
//   landing  app/<slug>/page.tsx: metadata (title, description, canonical, robots, keywords, Open
//            Graph/Twitter image), WebPage JSON-LD through the site's JsonLd component, the element
//            tree (Header/Footer are the site's shared components); a sitemap entry when published
//            and indexable (app/sitemap.ts staticRoutes).
//   post     content/blog-posts/<slug>.tsx body component, a record appended to content/blog.ts
//            (the site's BlogPost type; coverImage added to the type when used) and the body
//            registered in app/blog/[slug]/page.tsx. Blog index, related posts, JSON-LD, robots and
//            the sitemap then come from the site's own blog code (published posts only).
// Every insertion is anchored and refuses on drift (anchor missing or not unique).
// Revisit: when the site's blog or sitemap code changes. Last touched: 2026-11-23.
import {parse} from '@babel/parser'
import {routeOf, KIT_CODES} from '../../src/studio/live/pages.js'

const q = v => JSON.stringify(v)
const pascal = slug => slug.split('-').filter(Boolean).map(w => (/^\d/.test(w) ? 'N' + w : w[0].toUpperCase() + w.slice(1))).join('')
export const componentName = (kind, slug) => (kind === 'post' ? `StudioPost${pascal(slug)}Content` : `Studio${pascal(slug)}Page`)
const imageUrl = (ref, assetPath) => (ref ? (ref.startsWith('asset:') ? assetPath(ref) : ref) : '/images/site-og.png')
const once = (text, anchor, file) => {
 const parts = text.split(anchor)
 if (parts.length !== 2) throw Error(`Website source drift: ${file} no longer contains "${anchor.slice(0, 60)}" exactly once.`)
}

// Imports a created document needs, from what its tree uses (collected by the generator).
export function createdImports(needed) {
 const lines = []
 if (needed.has('Link')) lines.push('import Link from "next/link";')
 if (needed.has('Image')) lines.push('import Image from "next/image";')
 for (const code of Object.values(KIT_CODES)) if (needed.has(`kit:${code.kit.name}`)) lines.push(`import ${code.kit.name} from "${code.kit.from}";`)
 for (const item of [...needed].filter(n => n.startsWith('comp:')).sort()) { const [, name, from] = item.split(':'); lines.push(`import ${name} from "${from}";`) }
 if (needed.has('Fragment')) lines.push('import { Fragment } from "react";')
 return lines
}

export function landingSource(doc, s, jsx, needed, {assetPath = a => a} = {}) {
 const route = routeOf(doc, s)
 const title = s.seoTitle || s.title
 const og = imageUrl(s.ogImage, assetPath)
 const index = s.status === 'published' && !s.noindex
 const lines = ['// Generated by TTROS Website Studio: owner-created landing page. Edit it in the Studio; regenerated on every build.',
  'import type { Metadata } from "next";', 'import JsonLd from "@/components/JsonLd";', 'import { SITE } from "@/lib/config";', ...createdImports(needed), '',
  'export const metadata: Metadata = {',
  `  title: ${q(title)},`, `  description: ${q(s.description)},`,
  `  alternates: { canonical: \`\${SITE.domain}${route}\` },`,
  `  robots: { index: ${index}, follow: ${s.status === 'published'} },`,
  ...(s.keywords?.length ? [`  keywords: ${q(s.keywords)},`] : []),
  '  openGraph: {', '    type: "website",', `    title: ${q(`${title} | Example Company`)},`, `    description: ${q(s.description)},`, `    url: \`\${SITE.domain}${route}\`,`,
  `    images: [{ url: \`\${SITE.domain}${og}\`, width: 1200, height: 630, alt: ${q(s.ogImageAlt || s.title)} }],`, '  },',
  '  twitter: {', '    card: "summary_large_image",', `    title: ${q(`${title} | Example Company`)},`, `    description: ${q(s.description)},`, `    images: [\`\${SITE.domain}${og}\`],`, '  },', '};', '',
  'const webPageSchema = {', '  "@context": "https://schema.org",', '  "@type": "WebPage",', `  "@id": \`\${SITE.domain}${route}#webpage\`,`, `  name: ${q(s.title)},`,
  `  url: \`\${SITE.domain}${route}\`,`, `  description: ${q(s.description)},`, '  isPartOf: { "@id": `${SITE.domain}/#website` },', '  about: { "@id": `${SITE.domain}/#organization` },', '};', '',
  `export default function ${componentName('landing', s.slug)}() {`, '  return (', '<>', '<JsonLd data={webPageSchema} />', jsx, '</>', '  );', '}', '']
 return lines.join('\n')
}

export function postSource(doc, s, jsx, needed) {
 return ['// Generated by TTROS Website Studio: owner-created blog post body (its record is in content/blog.ts). Edit it in the Studio.',
  ...createdImports(needed), '', `export default function ${componentName('post', s.slug)}() {`, '  return (', '<>', jsx, '</>', '  );', '}', ''].join('\n')
}

// Words of a post body (reading time when the owner sets none).
export function words(tree) {
 let n = 0
 const visit = list => { for (const item of list || []) { if (item.type === 'Txt') n += String(item.props.text).trim().split(/\s+/).filter(Boolean).length; for (const k of ['kids', 'alt']) visit(item.props[k]) } }
 visit(tree)
 return n
}

function arrayEnd(text, name, file) {
 const ast = parse(text, {sourceType: 'module', plugins: ['typescript', 'jsx']})
 let found = null
 const visit = node => {
  if (!node || typeof node !== 'object' || found) return
  if (node.type === 'VariableDeclarator' && node.id?.type === 'Identifier' && node.id.name === name && node.init?.type === 'ArrayExpression') { found = node.init; return }
  for (const k of Object.keys(node)) if (k !== 'loc' && k !== 'start' && k !== 'end') { const v = node[k]; if (Array.isArray(v)) v.forEach(visit); else if (v && typeof v.type === 'string') visit(v) }
 }
 visit(ast.program)
 if (!found) throw Error(`Website source drift: ${file} has no ${name} array.`)
 // Insert after the last element and its comma (adding the comma when the source has none).
 const last = found.elements.at(-1)
 if (!last) return {text, at: found.start + 1}
 const tail = text.slice(last.end, found.end - 1)
 const comma = tail.indexOf(',')
 if (comma >= 0) return {text, at: last.end + comma + 1}
 return {text: text.slice(0, last.end) + ',' + text.slice(last.end), at: last.end + 1}
}

function postRecord(s, tree) {
 const lines = ['  // ── Created in TTROS Website Studio ──', '  {', `    title: ${q(s.title)},`]
 if (s.seoTitle) lines.push(`    seoTitle: ${q(s.seoTitle)},`)
 lines.push(`    slug: ${q(s.slug)},`, `    description: ${q(s.description)},`, `    excerpt: ${q(s.excerpt || s.description)},`, `    date: ${q(s.date)},`)
 if (s.updatedDate) lines.push(`    updatedDate: ${q(s.updatedDate)},`)
 lines.push(`    category: ${q(s.category)},`, `    tags: ${q(s.tags || [])},`, `    targetKeyword: ${q(s.targetKeyword || s.title.toLowerCase())},`,
  `    secondaryKeywords: ${q(s.secondaryKeywords || [])},`, `    readingTime: ${q(s.readingTime || `${Math.max(1, Math.round(words(tree) / 220))} min read`)},`, `    status: ${q(s.status)},`)
 if (s.coverImageAlt || s.coverImage) lines.push(`    coverImageAlt: ${q(s.coverImageAlt || s.title)},`)
 if (s.coverImage) lines.push(`    coverImage: ${q(s.coverImage)},`)
 if (s.pillar) lines.push(`    pillar: ${q(s.pillar)},`)
 if (s.relatedPosts?.length) lines.push(`    relatedPosts: ${q(s.relatedPosts)},`)
 lines.push('  },')
 return lines.join('\n')
}

// Structural edits for created pages over the generated + code-layer output. `docs` holds the created
// documents' trees (reading time). Returns the full set of changed files.
export function applySitePages(pages, files, changed, docs = {}, {assetPath = a => a} = {}) {
 const out = {...changed}
 const entries = Object.entries(pages || {}).sort(([a], [b]) => a.localeCompare(b))
 if (!entries.length) return out
 const current = path => { const v = out[path] ?? files.get(path); if (v === undefined) throw Error(`Website source drift: ${path} is missing.`); return v }
 const posts = entries.filter(([, s]) => s.kind === 'post')
 if (posts.length) {
  // content/blog.ts: records appended to blogPosts (+ the coverImage field on the type when used).
  let blog = current('content/blog.ts')
  const covers = posts.some(([, s]) => s.coverImage)
  const end = arrayEnd(blog, 'blogPosts', 'content/blog.ts')
  const records = posts.map(([doc, s]) => postRecord({...s, ...(s.coverImage ? {coverImage: imageUrl(s.coverImage, assetPath)} : {})}, docs[doc])).join('\n')
  blog = end.text.slice(0, end.at) + '\n' + records + end.text.slice(end.at)
  if (covers && !/\n\s*coverImage\?:/.test(blog)) {
   const anchor = '  coverImageAlt?: string;\n'
   once(blog, anchor, 'content/blog.ts')
   blog = blog.replace(anchor, anchor + '  coverImage?: string; // TTROS Website Studio: cover and social image of a post\n')
  }
  out['content/blog.ts'] = blog
  // app/blog/[slug]/page.tsx: import + registry entry for each post body.
  const file = 'app/blog/[slug]/page.tsx'
  let page = current(file)
  const importAnchor = '// Import published post content components here as posts go live.\n'
  const registry = 'const publishedComponents: Record<string, React.ComponentType> = {\n'
  once(page, importAnchor, file); once(page, registry, file)
  page = page.replace(importAnchor, importAnchor + posts.map(([, s]) => `import ${componentName('post', s.slug)} from "@/content/blog-posts/${s.slug}";\n`).join(''))
  page = page.replace(registry, registry + posts.map(([, s]) => `  ${q(s.slug)}: ${componentName('post', s.slug)},\n`).join(''))
  if (covers) {
   const og = '`${SITE.domain}/images/site-og.png`'
   const meta = page.indexOf('export async function generateMetadata')
   const metaEnd = page.indexOf('\n}\n', meta)
   const head = page.slice(meta, metaEnd)
   if (meta < 0 || metaEnd < 0 || head.split(og).length !== 3) throw Error(`Website source drift: ${file} generateMetadata no longer uses the default social image twice.`)
   page = page.slice(0, meta) + head.split(og).join('`${SITE.domain}${post.coverImage ?? "/images/site-og.png"}`') + page.slice(metaEnd)
  }
  out[file] = page
 }
 const listed = entries.filter(([, s]) => s.kind === 'landing' && s.status === 'published' && !s.noindex)
 if (listed.length) {
  let map = current('app/sitemap.ts')
  const end = arrayEnd(map, 'staticRoutes', 'app/sitemap.ts')
  const rows = listed.map(([doc, s]) => ['    {', `      url: \`\${base}${routeOf(doc, s)}\`,`, '      lastModified: now,', '      changeFrequency: "monthly",', '      priority: 0.7,', '    },'].join('\n')).join('\n')
  map = end.text.slice(0, end.at) + '\n    // Created in TTROS Website Studio\n' + rows + end.text.slice(end.at)
  out['app/sitemap.ts'] = map
 }
 return out
}

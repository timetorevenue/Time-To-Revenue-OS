// Revisit: when Brain network interaction changes. Last touched: 2026-11-09.
import { chromium } from 'playwright'
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
const proofDir = path.resolve('../../workflows/queue_artifacts/brain_network_2026-11-09')
const browser = await chromium.launch({headless: true, executablePath: '/home/operator/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome', args: ['--no-sandbox']})
try {
  const page = await browser.newPage({viewport: {width: 1600, height: 1100}})
  page.setDefaultTimeout(65000)
  const errors = [], mutations = [], reads = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.method() !== 'GET') mutations.push(r.url()); if (r.url().includes('/api/dashboard/graphify')) reads.push(r.url()) })
  const loaded = page.waitForResponse(r => r.url().includes('/api/dashboard/graphify'))
  await page.goto('http://127.0.0.1:3010/search', {waitUntil: 'domcontentloaded'})
  await page.getByRole('button', {name: 'Graphify', exact: true}).first().click()
  const response = await loaded
  assert.equal(response.status(), 200)
  const payload = await response.json(), brain = payload.visibility.business_brain
  const start = Date.now()
  await page.getByRole('button', {name: 'Business Brain', exact: true}).click()
  const network = page.getByTestId('brain-network'), svg = page.getByTestId('brain-network-svg')
  await svg.waitFor()
  const renderMs = Date.now() - start, nodes = await page.getByTestId('brain-network-node').count()
  assert.ok(nodes >= brain.total)
  assert.equal(await svg.locator('line[data-suggested="true"]').count(), brain.suggested_edges)
  assert.ok(await svg.locator('line[data-suggested="false"]').count() >= brain.document_edges)
  await network.screenshot({path: path.join(proofDir, '01-whole-graph.png')})
  const camera = page.getByTestId('brain-network-camera'), original = await camera.getAttribute('transform')
  await network.getByRole('button', {name: 'Zoom in', exact: true}).click()
  assert.notEqual(await camera.getAttribute('transform'), original)
  await network.getByRole('button', {name: 'Fit / reset'}).click()
  assert.equal(await camera.getAttribute('transform'), original)
  const box = await svg.boundingBox()
  await page.mouse.move(box.x + 50, box.y + 50)
  await page.mouse.down()
  await page.mouse.move(box.x + 160, box.y + 100, {steps: 6})
  await page.mouse.up()
  assert.notEqual(await camera.getAttribute('transform'), original)
  const panned = await camera.getAttribute('transform')
  await page.mouse.wheel(0, -120)
  await page.waitForTimeout(200)
  assert.notEqual(await camera.getAttribute('transform'), panned)
  await page.getByLabel('Graph document filter').selectOption('unlinked')
  assert.equal(await page.getByTestId('brain-network-node').count(), brain.documents.filter(d => !d.connections.length && d.graph_status !== 'unknown').length)
  await page.getByLabel('Graph document filter').selectOption('connected')
  assert.equal(await page.getByTestId('brain-network-node').count(), brain.documents.filter(d => d.connections.length).length + nodes - brain.total)
  await page.getByLabel('Graph document filter').selectOption('all')
  const relation = brain.documents.flatMap(d => d.connections).find(l => l.path).relation
  await page.getByLabel('Graph relationship type').selectOption(relation)
  assert.ok(await svg.locator('line').count() > 0)
  assert.ok((await svg.locator('line title').allTextContents()).every(text => text.startsWith(relation)))
  await page.getByLabel('Graph relationship type').selectOption('')
  await page.getByLabel('Show suggested links').uncheck()
  assert.equal(await svg.locator('line[data-suggested="true"]').count(), 0)
  await page.getByLabel('Show suggested links').check()
  const target = brain.documents.find(d => d.path === 'business_brain:memory/company.md' && d.connections.some(l => l.path)) || brain.documents.find(d => d.connections.some(l => l.path))
  await page.getByLabel('Search graph', {exact: true}).fill(target.path)
  await page.getByLabel('Graph search results').getByRole('button').filter({hasText: target.path}).first().click()
  const node = svg.locator(`[data-node-id="${target.path}"]`)
  assert.equal(await node.getAttribute('aria-pressed'), 'true')
  await node.press('Enter')
  // Select a different inventory record, then prove a pointer click restores this graph node.
  const other = page.getByTestId('graphify-brain-document').filter({hasNotText: target.path}).first()
  await other.click()
  await node.locator('circle').click({force: true})
  assert.equal(await node.getAttribute('aria-pressed'), 'true')
  const detail = page.getByTestId('graphify-brain-detail')
  assert.equal(await detail.getByRole('link', {name: 'Open in Memory'}).getAttribute('href'), `/memory?record=${encodeURIComponent(target.path)}`)
  assert.ok(await svg.locator('line[data-highlighted="true"]').count() > 0)
  await network.getByRole('button', {name: 'Fit connections', exact: true}).click()
  await network.screenshot({path: path.join(proofDir, '02-selected-connections.png')})
  await detail.screenshot({path: path.join(proofDir, '03-node-details.png')})
  assert.equal(reads.length, 1)
  const inventory = page.getByTestId('graphify-brain-inventory')
  await inventory.getByRole('button', {name: 'Next', exact: true}).click()
  assert.match(await inventory.innerText(), /Page 2 of/)
  await page.getByLabel('Search Business Brain inventory').fill(target.path)
  assert.equal(await page.getByTestId('graphify-brain-document').count(), 1)
  await page.getByTestId('graphify-brain-document').click()
  const memoryLoaded = page.waitForResponse(r => r.url().includes('/api/memory/document?'))
  await detail.getByRole('link', {name: 'Open in Memory'}).click()
  assert.equal((await memoryLoaded).status(), 200)
  await page.getByText('Technical details', {exact: true}).waitFor()
  await page.screenshot({path: path.join(proofDir, '04-memory-reader.png'), fullPage: true})
  await page.goBack({waitUntil: 'domcontentloaded'})
  await page.getByRole('button', {name: 'Graphify', exact: true}).first().click()
  await page.getByRole('button', {name: 'Code Repositories', exact: true}).click()
  await page.getByTestId('graphify-repository-coverage').getByText('owner-gh-account/TTROS', {exact: true}).waitFor()
  if (payload.repos.length) {
    const graph = page.frameLocator('[data-testid="graphify-graph-preview"]')
    await graph.locator('.node circle').last().click()
    await graph.locator('#details:not([hidden])').waitFor()
    await page.frameLocator('[data-testid="graphify-tree-preview"]').locator('body').waitFor()
    await page.getByRole('button', {name: 'Report', exact: true}).click()
    await page.getByText('Loading…', {exact: true}).waitFor({state: 'hidden'})
    await page.screenshot({path: path.join(proofDir, '05-repository-regression.png'), fullPage: true})
  }
  assert.deepEqual(errors, [])
  assert.deepEqual(mutations, [])
  fs.writeFileSync(path.join(proofDir, 'browser-proof.json'), JSON.stringify({passed: true, documents: brain.total, nodes, documentEdges: brain.document_edges, suggestions: brain.suggested_edges, renderMs, initialCoverageReads: 1, coverageReadsAfterNavigation: reads.length, memoryRecord: target.path, checks: ['whole graph', 'zoom/reset/pan/wheel', 'coverage and relationship filters', 'suggestion toggle', 'search focus', 'keyboard and pointer selection', 'highlighting', 'Memory HTTP 200', 'no extra coverage reads', 'inventory pagination/search', 'repository graph selection/tree/report', 'no mutations/page errors'], errors, mutations}, null, 2))
} finally { await browser.close() }

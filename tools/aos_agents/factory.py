"""Agent Factory v0: build a TAP agent package from a build spec and gate it.

A build spec is a folder under ``agents/factory/specs/<name>/``: ``spec.toml``,
the I/O schemas, the golden cases, the handler and one or more prompt variants.
``build`` runs the whole loop in a fixed order and stops at the first step that
fails:

  spec      load and validate the spec
  registry  refuse to overwrite a hand-built or promoted package; list similar agents
  cases     schemas and golden cases come first: composition, safety probes, inputs
  assessment  on substantive Git changes, decide reuse, extend or new before scaffolding
  scaffold  write the package; every file is derived from the spec
  check     gate 1
  optimise  try candidates (prompt x model x effort) cheapest first on the training
            cases, inside a fixed token budget; the first that passes is pinned
  eval      gates 1-6 on every case, including the held-out ones the optimiser never saw
  review    on substantive Git changes, independently review the diff and affected interfaces
  report    evidence/factory.json
  pack      a reproducible archive of the package and its evidence
  register  record the package in agents/registry.lock.json as a candidate

The package is a pure function of the spec and the chosen candidate, so "no hand
edits" is checkable: ``verify`` regenerates the files and compares them. Model
replies are recorded and reused, so a rebuild of an unchanged spec costs nothing.
The Factory creates candidates only; promotion is registry.promote.

Revisit: when the TAP schema, the acceptance gate or the spec layout changes. · Last touched: 2026-11-14.
"""


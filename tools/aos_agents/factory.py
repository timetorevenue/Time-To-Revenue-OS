def new_spec(name: str, kind: str, root: Path | None = None, *, summary: str = "", requirement: str = "") -> dict:
    """Scaffold a build spec from the template for ``kind``. Refuses to overwrite one."""
    root = repo_root(root)
    try:
        parsed, version = parse_ref(name)
    except PackageError as exc:
        raise FactoryError(str(exc)) from exc
    template = TEMPLATES_DIR / kind
    if version is not None or not template.is_dir():
        raise FactoryError(f"new takes department.capability and a kind with a template ({', '.join(sorted(p.name for p in TEMPLATES_DIR.iterdir() if p.is_dir()))})")
    directory = root / SPECS_DIR / parsed
    if directory.exists():
        raise FactoryError(f"a spec already exists at {(SPECS_DIR / parsed).as_posix()}")
    if (root / PACKAGES_DIR / parsed).exists():
        raise FactoryError(f"{parsed} is already installed; choose another name or bump its spec")
    summary = summary.strip() or f"TODO: one sentence saying what {parsed} does."
    requirement = requirement.strip() or f"TODO: what {parsed} is for, who calls it and what it must never do."
    swaps = {"@@NAME@@": parsed, "@@SUMMARY@@": json.dumps(summary, ensure_ascii=False),
             "@@REQUIREMENT@@": json.dumps(requirement, ensure_ascii=False)}
    written = []
    for source in sorted(p for p in template.rglob("*") if p.is_file() and "__pycache__" not in p.parts):
        text = source.read_text(encoding="utf-8")
        for token, value in swaps.items():
            text = text.replace(token, value)
        relative = source.relative_to(template).as_posix().removesuffix(".tmpl")
        target = directory / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(relative)
    return {"spec": (SPECS_DIR / parsed).as_posix(), "kind": kind, "files": written,
            "next": f"complete the schemas and golden cases first, then the handler and prompt; run aos-agent.py build {parsed}"}


# -- queue work order -----------------------------------------------------------

def work_order_spec(item: dict | None) -> dict | None:
    spec = (item or {}).get("executor")
    if not isinstance(spec, dict) or spec.get("kind") != WORK_ORDER_KIND or spec.get("action") != WORK_ORDER_ACTION:
        return None
    return spec


def is_factory_item(item: dict | None) -> bool:
    return work_order_spec(item) is not None


def run_work_order(root: Path, item: dict, *, modelport: Callable[..., dict] | None = None,
                   scoped_reader: Callable[[str, str], dict] | None = None, ledger_root: Path | None = None,
                   backend: str = "exec", quota: Callable[[], dict] | None = None, codex_account: Any = None) -> dict:
    """Run a ``factory.build_agent`` queue item and return the worker-result shape the closeout consumes.

        "executor": {"kind": "factory", "action": "build_agent", "spec": "crm.meeting_extract",
                     "live": true, "token_budget": 240000}

    The item names a spec that already exists; writing the spec is the coding half of the
    work order (queue/templates/factory_build_agent.prompt.md). Real calls need ``live``
    and, unless a model is injected, a subscription usage window below the quota limit.
    """
    from .executor import _one_line, _token_usage

    order = work_order_spec(item) or {}
    item_id, target = str(item.get("id") or ""), str(order.get("spec") or "")
    live = order.get("live") is True
    budget = order.get("token_budget")
    if not item_id or not target or (budget is not None and (not isinstance(budget, int) or isinstance(budget, bool) or budget < 0)):
        report: dict[str, Any] = {"status": "failed", "failed_step": "work_order", "agent": target, "steps": [], "level": "none",
                                  "detail": "the work order needs an item id, a spec name and, if given, a whole-number token_budget"}
    else:
        gate = {"ok": True}
        if live and modelport is None:
            if codex_account is None:
                from aos_codex_policy import AccountPin

                codex_account = AccountPin()
            pin = codex_account
            gate = (quota or (lambda: quota_preflight(reader=lambda: _read_rate_limits(pin))))()
        if not gate["ok"]:
            report = {"status": "failed", "failed_step": "quota", "agent": target, "steps": [], "level": "none",
                      "detail": gate.get("detail", "quota check failed"), "quota": gate}
        else:
            report = build(target, root, live=live, modelport=modelport, scoped_reader=scoped_reader,
                           ledger_root=ledger_root, backend=backend, token_budget=budget, work_order=item_id,
                           codex_account=codex_account)
            if gate.get("used_percent") is not None:
                report["quota"] = gate   # the preflight reading, advisory included, for the evidence
    passed = report["status"] in ("candidate", "reused")
    reused = report["status"] == "reused"
    tokens = report.get("tokens") or {}
    usage = {"model_calls": tokens.get("live_calls", 0), "exact": tokens.get("exact", True),
             "input_tokens": tokens.get("input_tokens", 0), "output_tokens": tokens.get("output_tokens", 0),
             "cached_input_tokens": tokens.get("cached_input_tokens", 0),
             "total_tokens": tokens.get("input_tokens", 0) + tokens.get("output_tokens", 0)}
    token_usage, token_text = _token_usage(usage)
    steps = ", ".join(f"{row['step']} {'ok' if row['ok'] else 'FAILED'}" for row in report.get("steps") or []) or "no step ran"
    failed = next((row for row in report.get("steps") or [] if not row["ok"]), None)
    reason = report.get("detail") or _one_line(json.dumps({k: v for k, v in (failed or {}).items() if k not in ("step", "ok")}, ensure_ascii=False), 500)
    files = [str(path) for path in (report.get("spec"), report.get("evidence"), (report.get("archive") or {}).get("archive"),
                                    registry.REGISTRY_PATH.as_posix() if passed and not reused else None) if path]
    supports = ", ".join(report.get("supports") or []) or "no release state"
    lines = [
        "PASS" if passed else "NEEDS ATTENTION",
        f"Summary for operator: Factory build of {report.get('agent') or target} "
        + ("identified an existing implementation to reuse." if reused else
           f"produced a packed candidate at {report['level']}; evidence supports {supports}. Nothing was promoted or routed."
           if passed else f"stopped at step {report.get('failed_step') or 'unknown'}."),
        f"Files touched: {', '.join(files) if files else 'None'}",
        f"Validation: {steps}",
        "Connector access: No connector action",
        token_text,
        f"Blockers: {'None' if passed else reason}",
        f"Next action: {'Use the existing implementation cited in the assessment' if reused else 'Casey may promote it to shadow with aos-agent.py promote' if passed else 'Fix the spec and re-run the work order'}",
    ]
    return {
        "success": passed, "returncode": 0 if passed else 1, "output": "\n".join(lines), "stdout": "", "stderr": "",
        "timed_out": False, "command_stage": "completion" if passed else "agent_factory",
        "failure_class": "" if passed else "factory_build_failed", "failure_detail": "" if passed else reason,
        "elapsed_seconds": report.get("elapsed_seconds", 0.0), "token_usage": token_usage, "token_usage_text": token_text,
        # ModelPort already wrote each live call to the token ledger; the closeout must not log it again.
        "token_usage_logged": True, "file_changes": files, "session_id": "", "agent_ref": report.get("agent") or target,
        "brain_context_used": [],   # a build's eval reads are fixtures, not scoped Brain reads
        "factory_report": report,
    }

class FactoryError(RuntimeError):
    """The spec is missing or malformed, or the build cannot proceed as asked."""


@dataclass(frozen=True)
class BuildSpec:
    name: str
    version: str
    kind: str
    directory: Path
    data: dict
    sha256: str
    candidates: tuple[dict, ...]
    token_budget: int
    holdout_share: float

    @property
    def ref(self) -> str:
        return f"{self.name}@{self.version}"


# -- spec -----------------------------------------------------------------------

def _spec_file(directory: Path, relative: str, what: str) -> Path:
    target = (directory / relative).resolve()
    if not target.is_relative_to(directory.resolve()) or not target.is_file():
        raise FactoryError(f"{what} is missing from the spec: {relative}")
    return target


def load_spec(ref: str, root: Path | None = None) -> BuildSpec:
    root = repo_root(root)
    try:
        name, version = parse_ref(ref)
    except PackageError as exc:
        raise FactoryError(str(exc)) from exc
    directory = root / SPECS_DIR / name
    try:
        data = tomllib.loads((directory / "spec.toml").read_text(encoding="utf-8"))
    except OSError as exc:
        raise FactoryError(f"no build spec at {(SPECS_DIR / name / 'spec.toml').as_posix()}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise FactoryError(f"{name}: spec.toml is unreadable: {exc}") from exc
    unknown = sorted(set(data) - SPEC_TABLES)
    missing = sorted({"agent", "io", "capabilities", "budget", "factory"} - set(data))
    if unknown or missing:
        raise FactoryError(f"{name}: spec.toml has unknown table(s) {unknown} or lacks {missing}")
    agent, factory = data["agent"], data["factory"]
    if agent.get("name") != name:
        raise FactoryError(f"{name}: spec folder does not match agent.name {agent.get('name')!r}")
    if version is not None and version != agent.get("version"):
        raise FactoryError(f"{name}: version {version} requested, the spec is {agent.get('version')}")
    kind = agent.get("kind")
    if kind not in BUILDABLE_KINDS:
        raise FactoryError(f"{name}: kind {kind!r} is not built by this Factory version (builds {', '.join(BUILDABLE_KINDS)})")
    requirement = factory.get("requirement")
    if not isinstance(requirement, str) or not 20 <= len(requirement.strip()) <= 2400:
        raise FactoryError(f"{name}: factory.requirement must say what the agent is for")
    share = factory.get("holdout_share", DEFAULT_HOLDOUT_SHARE)
    if not isinstance(share, (int, float)) or isinstance(share, bool) or not 0 <= share <= MAX_HOLDOUT_SHARE:
        raise FactoryError(f"{name}: factory.holdout_share must be between 0 and {MAX_HOLDOUT_SHARE}")
    budget = factory.get("token_budget", 0)
    if not isinstance(budget, int) or isinstance(budget, bool) or budget < 0:
        raise FactoryError(f"{name}: factory.token_budget must be a whole number of tokens")
    dependencies = factory.get("dependencies", [])
    if (not isinstance(dependencies, list) or len(dependencies) > engineering.MAX_DEPENDENCIES
            or any(not isinstance(path, str) for path in dependencies)):
        raise FactoryError(f"{name}: factory.dependencies must be a bounded list of repository source paths")
    for required in ("handler.py", evals.CASES_PATH, str(data["io"].get("input_schema")), str(data["io"].get("output_schema"))):
        _spec_file(directory, required, "a required file")

    candidates = factory.get("candidates") or []
    if kind == "tool":
        if candidates:
            raise FactoryError(f"{name}: a tool agent has no model, so it has no candidates")
        candidates = [{}]
    else:
        if not isinstance(candidates, list) or not 1 <= len(candidates) <= MAX_CANDIDATES:
            raise FactoryError(f"{name}: factory.candidates needs 1 to {MAX_CANDIDATES} entries, cheapest first")
        seen = set()
        for candidate in candidates:
            if not isinstance(candidate, dict) or set(candidate) != {"prompt", "model", "effort"}:
                raise FactoryError(f"{name}: each candidate names exactly prompt, model and effort")
            _spec_file(directory, str(candidate["prompt"]), "a candidate prompt")
            key = (candidate["prompt"], candidate["model"], candidate["effort"])
            if key in seen:
                raise FactoryError(f"{name}: candidate listed twice: {key}")
            seen.add(key)
    return BuildSpec(name=name, version=str(agent.get("version")), kind=kind, directory=directory, data=data,
                     sha256=content_hash(directory), candidates=tuple(dict(c) for c in candidates),
                     token_budget=budget, holdout_share=float(share))


def specs(root: Path | None = None) -> list[str]:
    directory = repo_root(root) / SPECS_DIR
    return sorted(p.name for p in directory.iterdir() if (p / "spec.toml").is_file()) if directory.is_dir() else []


# -- generation -----------------------------------------------------------------

def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    raise FactoryError(f"value cannot be written to a manifest: {value!r}")


def manifest_for(spec: BuildSpec, candidate: dict) -> dict:
    data = spec.data
    manifest: dict[str, Any] = {"agent": {**{k: v for k, v in data["agent"].items()}, "tap": "0.1"}}
    if spec.kind != "tool":
        prompt = _spec_file(spec.directory, candidate["prompt"], "a candidate prompt").read_bytes()
        manifest["model"] = {"id": candidate["model"], "effort": candidate["effort"],
                             "prompt_sha256": hashlib.sha256(prompt).hexdigest(), "escalate_to": ""}
    for table in ("io", "context", "capabilities", "budget", "compose"):
        if table in data:
            manifest[table] = dict(data[table])
    manifest["acceptance"] = {"level": "none"}   # the level is read from evidence, never stored here
    return manifest


def render_manifest(spec: BuildSpec, candidate: dict) -> str:
    manifest = manifest_for(spec, candidate)
    lines = [f"{GENERATED_MARK} {FACTORY_VERSION} from {(SPECS_DIR / spec.name).as_posix()}. Edit the spec and rebuild; do not edit this file."]
    for table, body in manifest.items():
        lines += ["", f"[{table}]"] + [f"{key} = {_toml_value(value)}" for key, value in body.items()]
    text = "\n".join(lines) + "\n"
    if tomllib.loads(text) != manifest:
        raise FactoryError(f"{spec.name}: the generated manifest does not read back as written")
    return text


def expected_files(spec: BuildSpec, candidate: dict) -> dict[str, bytes]:
    """Every file of the package, derived from the spec and one candidate. Pure."""
    directory = spec.directory
    files = {"agent.toml": render_manifest(spec, candidate).encode("utf-8"),
             "handler.py": (directory / "handler.py").read_bytes(),
             evals.CASES_PATH: (directory / evals.CASES_PATH).read_bytes()}
    if spec.kind != "tool":
        files[PROMPT_PATH] = (directory / candidate["prompt"]).read_bytes()
    for path in sorted((directory / "schemas").glob("*.json")):
        files[f"schemas/{path.name}"] = path.read_bytes()
    for optional in ("evals/rubric.md", "NOTICE", "LICENSE"):
        if (directory / optional).is_file():
            files[optional] = (directory / optional).read_bytes()
    return files


def _package_files(directory: Path) -> dict[str, Path]:
    found = {}
    for path in directory.rglob("*") if directory.is_dir() else []:
        relative = path.relative_to(directory).as_posix()
        if path.is_file() and not relative.startswith(PRESERVED_PREFIXES) and "__pycache__" not in relative:
            found[relative] = path
    return found


def materialise(spec: BuildSpec, candidate: dict, root: Path) -> Path:
    """Write the package for one candidate. Recorded replies and evidence are kept."""
    directory = root / PACKAGES_DIR / spec.name
    files = expected_files(spec, candidate)
    for relative, path in _package_files(directory).items():
        if relative not in files:
            path.unlink()
    for relative, data in files.items():
        target = directory / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_file() or target.read_bytes() != data:
            target.write_bytes(data)
    return directory


def hand_edits(spec: BuildSpec, candidate: dict, root: Path) -> dict:
    """How the package on disk differs from what the spec generates. All empty means none."""
    expected = expected_files(spec, candidate)
    actual = _package_files(root / PACKAGES_DIR / spec.name)
    return {"changed": sorted(r for r in expected if r in actual and actual[r].read_bytes() != expected[r]),
            "missing": sorted(r for r in expected if r not in actual),
            "extra": sorted(r for r in actual if r not in expected)}


# -- checks before any model call -------------------------------------------------

def holdout_ids(cases: list[dict], share: float) -> list[str]:
    """The cases the optimiser never sees: those tagged ``holdout``, else a fixed pseudo-random share."""
    tagged = sorted(case["id"] for case in cases if "holdout" in (case.get("tags") or []))
    if tagged or not share:
        return tagged
    ranked = sorted((case["id"] for case in cases), key=lambda ident: hashlib.sha256(ident.encode("utf-8")).hexdigest())
    return sorted(ranked[:math.ceil(share * len(ranked))])


def check_eval_set(spec: BuildSpec) -> dict:
    """Schemas and golden cases come first: the set must be complete before anything is built."""
    problems: list[str] = []
    schemas = {}
    for key in ("input_schema", "output_schema"):
        relative = spec.data["io"][key]
        try:
            schemas[key] = json.loads((spec.directory / relative).read_text(encoding="utf-8"))
            jsonschema.Draft202012Validator.check_schema(schemas[key])
        except (ValueError, jsonschema.SchemaError) as exc:
            problems.append(f"{relative} is not a valid JSON Schema: {str(exc)[:160]}")
    try:
        data = evals.load_cases(SimpleNamespace(directory=spec.directory, name=spec.name))
    except evals.EvalError as exc:
        return {"problems": problems + [str(exc)], "composition": None, "probes": [], "holdout": []}
    cases = data["cases"]
    composition = evals.case_composition(cases)
    if composition["short_of"]:
        problems.append("the golden set is short of the minimum: " + ", ".join(
            f"{tag} {composition[tag]}/{need}" for tag, need in composition["short_of"].items()))
    probes = sorted({tag.split(":", 1)[1] for case in cases for tag in case.get("tags") or [] if str(tag).startswith("safety:")})
    needed = SAFETY_PROBES if spec.kind != "tool" else ()
    lacking = [probe for probe in needed if probe not in probes]
    if lacking or not probes:
        problems.append("safety probes missing: " + (", ".join(lacking) or "at least one safety:<probe> case"))
    if "input_schema" in schemas:
        for case in cases:
            wrong = _schema_error(case["input"], schemas["input_schema"])
            if wrong and case["expect"].get("failure_class") != "input_schema_violation":
                problems.append(f"case {case['id']}: input does not match the input schema ({wrong[:120]})")
    holdout = holdout_ids(cases, spec.holdout_share)
    if spec.kind != "tool" and not (data.get("baseline") or {}).get("tokens"):
        problems.append("cases.json names no baseline.tokens, so gate 6 could never pass")
    return {"problems": problems, "composition": composition, "probes": probes, "holdout": holdout,
            "train": sorted(case["id"] for case in cases if case["id"] not in holdout)}


def _words(text: str) -> set[str]:
    return {word for word in re.findall(r"[a-z]{4,}", str(text).lower())}


def registry_check(spec: BuildSpec, root: Path) -> dict:
    """Is the name free to build, and does a similar agent already exist?"""
    problems: list[str] = []
    entry = registry.load(root)["agents"].get(spec.name)
    manifest = root / PACKAGES_DIR / spec.name / "agent.toml"
    if manifest.is_file() and not manifest.read_text(encoding="utf-8").startswith(GENERATED_MARK):
        problems.append(f"{spec.name} is installed and was not built by the Factory; it will not be overwritten")
    if entry and entry.get("state") != "candidate" and (entry.get("built") or {}).get("spec_sha256") != spec.sha256:
        problems.append(f"{spec.name}@{entry.get('version')} is promoted to {entry.get('state')}; "
                        "bump the version in the spec or demote it before rebuilding")
    mine, similar = _words(spec.data["agent"].get("summary", "")), []
    for name in installed(root):
        if name == spec.name:
            continue
        try:
            other = _words(load_package(name, root).manifest["agent"]["summary"])
        except PackageError:
            continue
        overlap = len(mine & other) / len(mine | other) if mine | other else 0.0
        if overlap >= SIMILARITY_NOTE_AT:
            similar.append({"agent": name, "summary_overlap": round(overlap, 2)})
    return {"problems": problems, "similar": similar, "registered": bool(entry)}


# -- budget ---------------------------------------------------------------------

def _ledger_job(work_order: str) -> str:
    from aos_job_ids import JOB_ID_RE
    return work_order if JOB_ID_RE.fullmatch(work_order) else ""


class BudgetedPort:
    """Wraps the live model call with the build's token budget.

    A call is refused, as data, when the budget cannot cover a worst-case call.
    Usage that comes back unknown is charged at that worst case, never at zero.
    Once the provider reports its own usage limit or an authentication failure, every
    later call is refused without reaching the provider.
    """

    def __init__(self, port: Callable[..., dict], limit: int, reserve: int, *, ledger: bool, work_item_id: str = ""):
        self.port, self.limit, self.reserve, self.ledger = port, int(limit), int(reserve), ledger
        self.work_item_id = work_item_id
        self.calls = self.refused = self.spent = 0
        self.usage = {"input_tokens": 0, "output_tokens": 0, "cached_input_tokens": 0}
        self.exact = True
        self.provider_stop = ""

    def affords(self, calls: int, *, retain: int = 0) -> bool:
        return self.spent + calls * self.reserve + retain <= self.limit

    def __call__(self, prompt: str, **kwargs: Any) -> dict:
        reserve = kwargs.pop("_reserve", self.reserve)
        if self.provider_stop:
            self.refused += 1
            return {"status": "failed", "failure_class": self.provider_stop, "usage": {"available": False},
                    "detail": f"the provider reported {self.provider_stop} earlier in this build; no further call is made"}
        if self.spent + reserve > self.limit:
            self.refused += 1
            return {"status": "failed", "failure_class": "factory_budget_exhausted", "usage": {"available": False},
                    "detail": f"the build's token budget ({self.limit}) cannot cover another call; {self.spent} spent"}
        if self.ledger:
            kwargs = {**kwargs, "record": True}   # exact usage goes to the token ledger through ModelPort
        if self.work_item_id:
            kwargs["work_item_id"] = self.work_item_id
        result = self.port(prompt, **kwargs)
        self.calls += 1
        if result.get("failure_class") in PROVIDER_STOP_CLASSES:
            self.provider_stop = str(result["failure_class"])
        usage = result.get("usage") or {}
        if usage.get("available"):
            for key in self.usage:
                self.usage[key] += int(usage.get(key) or 0)
            self.spent += int(usage.get("input_tokens") or 0) + int(usage.get("output_tokens") or 0)
        else:
            self.exact = False
            self.spent += reserve
        return result

    def summary(self) -> dict:
        return {"limit": self.limit, "spent": self.spent, "live_calls": self.calls, "refused_calls": self.refused,
                "exact": self.exact, **self.usage, **({"provider_stop": self.provider_stop} if self.provider_stop else {})}


def _read_rate_limits(account: Any = None) -> dict:
    """The usage windows of the Codex account this build runs on (its AccountPin, else a fresh selection).

    No eligible account raises aos_codex_policy.AccountUnavailable, which the preflight reports as a stop."""
    import aos_modelport
    from aos_codex_policy import select_codex_account

    target = account.target() if account is not None else select_codex_account()
    with aos_modelport.AppServerSession(target=target) as session:
        return session.rate_limits()


def quota_preflight(advisory_used_percent: float = QUOTA_ADVISORY_USED_PERCENT, reader: Callable[[], dict] | None = None) -> dict:
    """Read the subscription's usage windows (no model call). Fails closed when they cannot be read.

    Only the provider's real limits block: a window at 100% used, ``ordinaryUsageAllowed``
    false, ``rateLimitReachedType`` set or ``spendControlReached`` true. A window at or above
    ``advisory_used_percent`` is reported in ``advisory`` and does not block (Casey, 2026-11-14). Per-work-order token budgets still apply in ``build``.
    """
    try:
        snapshot = (reader or _read_rate_limits)() or {}
    except Exception as exc:  # the CLI is missing, logged out or changed: do not spend blind
        return {"ok": False, "detail": f"rate limits could not be read: {type(exc).__name__}: {str(exc)[:160]}"}
    limits = snapshot.get("rateLimits") or {}
    used = {name: limits[name].get("usedPercent") for name in ("primary", "secondary") if isinstance(limits.get(name), dict)}
    unreadable = {name: value for name, value in used.items() if not isinstance(value, (int, float)) or isinstance(value, bool)}
    exhausted = {name: value for name, value in used.items() if name not in unreadable and value >= QUOTA_EXHAUSTED_PERCENT}
    high = {name: value for name, value in used.items() if name not in unreadable and advisory_used_percent <= value < QUOTA_EXHAUSTED_PERCENT}
    refused = snapshot.get("ordinaryUsageAllowed") is False or bool(limits.get("rateLimitReachedType")) \
        or limits.get("spendControlReached") is True
    ok = bool(used) and not unreadable and not exhausted and not refused
    if ok:
        detail = ""
    elif not used:
        detail = "no usable usage window in the snapshot"
    elif unreadable:
        detail = f"usage window(s) not readable: {unreadable}"
    elif exhausted:
        detail = f"provider usage window(s) exhausted: {exhausted}"
    else:
        detail = ("the provider reports a limit reached: "
                  f"ordinaryUsageAllowed={snapshot.get('ordinaryUsageAllowed')}, rateLimitReachedType={limits.get('rateLimitReachedType')}, "
                  f"spendControlReached={limits.get('spendControlReached')}")
    return {"ok": ok, "used_percent": used, "advisory_used_percent": advisory_used_percent,
            "advisory": (f"usage window(s) at or above {advisory_used_percent}% (informational, not a stop): {high}" if high else ""),
            "detail": detail}


# -- verdict for a subset of cases --------------------------------------------------

def split_verdict(rows: list[dict], *, with_repair_rate: bool = True) -> dict:
    """Gates 2-4 for a subset of case rows, using the acceptance thresholds."""
    ran = [row for row in rows if not row["not_recorded"]]
    called = [row for row in ran if row["model_calls"]]
    clean = [row for row in ran if not row["failures"].get("2") and not row["failures"].get("3")]
    verdict = {
        "cases": len(rows), "ran": len(ran), "passed": sum(1 for row in ran if row["passed"]),
        "pass_rate": round(len(clean) / len(ran), 3) if ran else 0.0,
        "not_recorded": [row["id"] for row in rows if row["not_recorded"]],
        "failed": {row["id"]: row["failures"] for row in ran if row["failures"]},
        "critical_failed": [row["id"] for row in ran if "critical" in row["tags"] and not row["passed"]],
        "schema_invalid": [row["id"] for row in ran if row["failure_class"] in evals.SCHEMA_FAILURES],
        "repair_rate": round(sum(1 for row in called if row["repair"]) / len(called), 3) if called else 0.0,
        "model_calls": sum(row["model_calls"] for row in ran), "tokens": sum(row["tokens"] for row in ran),
    }
    verdict["pass"] = bool(rows) and not verdict["not_recorded"] and verdict["pass_rate"] >= evals.FUNCTIONALITY_PASS_RATE \
        and not verdict["critical_failed"] and not verdict["schema_invalid"] \
        and not any(reasons.get("3") or reasons.get("4") for reasons in verdict["failed"].values()) \
        and (not with_repair_rate or verdict["repair_rate"] <= evals.REPAIR_RATE_MAX)
    return verdict


# -- the build loop -------------------------------------------------------------

def build(spec_ref: str, root: Path | None = None, *, live: bool = False, modelport: Callable[..., dict] | None = None,
          backend: str = "exec", session: Any = None, ledger_root: Path | None = None,
          scoped_reader: Callable[[str, str], dict] | None = None, token_budget: int | None = None,
          until: str = "register", work_order: str = "", codex_account: Any = None,
          connection_context: tuple | None = None) -> dict:
    """Run the build loop for one spec. Returns the build report; never raises for a failed step.

    ``live`` allows real model calls for replies that are not recorded yet, inside the
    token budget. ``token_budget`` may lower the spec's budget, never raise it.
    ``until`` stops after the named step ("optimise" to search without registering).
    """
    root = repo_root(root)
    started = time.monotonic()
    report: dict[str, Any] = {"factory": FACTORY_VERSION, "agent": str(spec_ref), "status": "failed", "failed_step": "",
                              "work_order": work_order, "live": bool(live), "steps": [], "level": "none"}

    def step(name: str, ok: bool, **detail: Any) -> bool:
        report["steps"].append({"step": name, "ok": bool(ok), **detail})
        if not ok:
            report["failed_step"] = name
        return bool(ok)

    def finish(status: str) -> dict:
        report["status"] = status
        report["elapsed_seconds"] = round(time.monotonic() - started, 3)
        return report

    try:
        spec = load_spec(spec_ref, root)
    except FactoryError as exc:
        step("spec", False, problems=[str(exc)])
        return finish("failed")
    spec_path = (SPECS_DIR / spec.name).as_posix()
    report.update(agent=spec.ref, kind=spec.kind, spec=spec_path, spec_sha256=spec.sha256)
    # Discovery is evidence, never a portable provider grant. Runtime resolves again.
    manifest = manifest_for(spec, spec.candidates[0])
    requirements = [g for g in manifest['capabilities'].get('grants', []) if g.startswith(('connector.read:', 'connector.write:'))]
    if connection_context is not None:
        hub, who = connection_context
        discovery = hub.resolve(who, manifest)
        # Build evidence is portable and may be archived. Never embed a tenant's
        # account or binding identifiers in a package or its Factory report.
        report['connections'] = {**discovery,
                                 'resolved': {grant: len(matches) for grant, matches in discovery['resolved'].items()}}
    else:
        report['connections'] = {'resolved': {}, 'missing_required': requirements, 'advisory': True}
    step("spec", True, candidates=len(spec.candidates))

    listing = registry_check(spec, root)
    if not step("registry", not listing["problems"], **listing):
        return finish("failed")
    eval_set = check_eval_set(spec)
    if not step("cases", not eval_set["problems"], **eval_set):
        return finish("failed")

    limit = spec.token_budget if token_budget is None else min(spec.token_budget, max(0, int(token_budget)))
    reserve = int(spec.data["budget"]["tokens"])   # the most one case may cost
    if modelport is None and live:
        import functools

        import aos_modelport
        from aos_codex_policy import AccountPin

        # One build is one job: every live call runs on the same Codex account.
        pinned = functools.partial(aos_modelport.call, account=codex_account if codex_account is not None else AccountPin())
        guard = BudgetedPort(pinned, limit, reserve, ledger=True, work_item_id=_ledger_job(work_order))
    else:
        guard = BudgetedPort(modelport or (lambda *_a, **_k: {"status": "failed", "failure_class": "no_model"}), limit, reserve, ledger=False,
                             work_item_id=_ledger_job(work_order))
    shared = {"backend": backend, "session": session, "ledger_root": ledger_root, "scoped_reader": scoped_reader}
    package_path = (PACKAGES_DIR / spec.name).as_posix()
    dependencies = spec.data["factory"].get("dependencies", [])
    entry = registry.load(root)["agents"].get(spec.name) or {}
    registered = (entry.get("built") or {}).get("spec_sha256") == spec.sha256
    source_report = root / package_path / REPORT_PATH
    prior = {}
    try:
        if source_report.is_file():
            prior = json.loads(source_report.read_text(encoding="utf-8"))
        base = engineering.head(root)
        patch = engineering.evidence(root, base, spec_path, package_path, dependencies, registered=registered) if base else ""
        original = spec.data["factory"]["requirement"]
        if patch:
            assessment = engineering.assess(root, spec.name, original, manifest, dependencies, base=base)
            assessment_key = engineering.digest({
                "base": base, "spec": spec.sha256, "patch": patch,
                "dependencies": assessment["dependency_context"],
            })
            report["engineering"] = {"base": base, "input_sha256": assessment_key,
                                     "patch_sha256": engineering.digest(patch)}
            old = prior.get("engineering") or {}
            cached = old if old.get("input_sha256") == assessment_key else {}
            design = cached.get("assessment")
            if design is None:
                if not live:
                    raise engineering.EngineeringError("substantive change requires a live engineering assessment; run assess for offline context")
                if guard.spent + (2 if until != "optimise" else 1) * engineering.RESERVE > limit:
                    raise engineering.EngineeringError("the build budget cannot cover engineering assessment and review")
                design = engineering.infer(guard, "assessment", assessment, ledger_root=ledger_root)
            report["engineering"]["assessment"] = design
            decision = design["result"]["decision"]
            if decision == "extend" and not any(row["ref"].partition("@")[0] == spec.name
                                                for row in assessment["components"]):
                raise engineering.EngineeringError("assessment calls for extending an existing component; update its spec")
            if decision == "reuse" and design["result"]["reuse_ref"] not in {
                row["ref"] for row in assessment["components"]
                if row["ref"].partition("@")[0] != spec.name or row["ref"] != spec.ref
            }:
                raise engineering.EngineeringError("the reuse decision did not name an existing implementation")
            step("assessment", True, decision=decision)
            if decision == "reuse":
                report["tokens"] = guard.summary()
                return finish("reused")
    except (engineering.EngineeringError, OSError, ValueError) as exc:
        step("assessment", False, problems=[str(exc)])
        report["tokens"] = guard.summary()
        return finish("failed")

    def run_cases(only: list[str] | None, write: bool) -> tuple[dict | None, str]:
        """Replay what is recorded; call the model only for the rest, and only if the budget covers it."""
        result = evals.evaluate(spec.name, root, only=only, write=write, scoped_reader=scoped_reader)
        missing = len(result.get("not_recorded") or [])
        if not missing:
            return result, ""
        if not live:
            return result, "not_recorded"
        if not guard.affords(missing, retain=engineering.RESERVE if patch and until != "optimise" else 0):
            return result, "skipped_budget"
        return evals.evaluate(spec.name, root, live=True, modelport=guard, reuse_recorded=True, only=only, write=write, **shared), ""

    materialise(spec, spec.candidates[0], root)
    step("scaffold", True, package=(PACKAGES_DIR / spec.name).as_posix(), files=len(expected_files(spec, spec.candidates[0])))
    gate1 = evals.check(spec.name, root)
    if not step("check", gate1["pass"], problems=gate1["problems"]):
        return finish("failed")

    chosen: dict | None = spec.candidates[0] if spec.kind == "tool" else None
    trials: list[dict] = []
    for index, candidate in enumerate(spec.candidates if spec.kind != "tool" else ()):
        materialise(spec, candidate, root)
        trial: dict[str, Any] = {"index": index, **candidate, "outcome": ""}
        trials.append(trial)
        gate1 = evals.check(spec.name, root)
        trial["package_sha256"] = gate1.get("package_sha256", "")
        if not gate1["pass"]:
            trial.update(outcome="gate1_failed", problems=gate1["problems"])
            continue
        before = guard.spent
        result, stopped = run_cases(eval_set["train"], write=False)
        trial["tokens_spent"] = guard.spent - before
        if stopped:
            trial.update(outcome=stopped, not_recorded=len(result["not_recorded"]))
            if stopped == "skipped_budget":
                break     # candidates are ordered cheapest first; a dearer one cannot fit either
            continue
        verdict = split_verdict(result["cases"])
        trial.update(outcome="passed" if verdict["pass"] else "failed", verdict=verdict)
        if verdict["pass"]:
            chosen = candidate
            break
    optimise = {"candidates": trials, "chosen": chosen, "training_cases": len(eval_set["train"]),
                "held_out_cases": eval_set["holdout"], "tokens": guard.summary()}
    report["optimise"], report["chosen"] = optimise, chosen
    if spec.kind != "tool":
        outcomes = [trial["outcome"] for trial in trials]
        hint = " (no recorded replies; run again with live calls allowed)" if "not_recorded" in outcomes else ""
        if not step("optimise", chosen is not None, outcomes=outcomes, detail="" if chosen else f"no candidate passed{hint}"):
            materialise(spec, spec.candidates[0], root)   # leave the package at the first candidate, not the last one tried
            report["tokens"] = guard.summary()
            return finish("failed")
    if until == "optimise":
        report["tokens"] = guard.summary()
        return finish("stopped")

    evidence, stopped = run_cases(None, write=True)
    report["tokens"] = guard.summary()
    rows = evidence.get("cases") or []
    held_out = [row for row in rows if row["id"] in eval_set["holdout"]]
    holdout = {"ids": eval_set["holdout"], **(split_verdict(held_out, with_repair_rate=False) if held_out else {"pass": True, "cases": 0})}
    report.update(level=evidence.get("level", "none"), binding=evidence.get("binding"), holdout=holdout,
                  package_sha256=evidence.get("package_sha256"), evidence=evidence.get("evidence_path"),
                  gates={gate: bool(body.get("pass")) for gate, body in (evidence.get("gates") or {}).items()},
                  totals=evidence.get("totals"))
    failed_cases = {row["id"]: row["failures"] for row in rows if row["failures"]}
    if not step("eval", evidence.get("level", "none") != "none", level=report["level"], gates=report["gates"],
                complete=evidence.get("complete"), stopped=stopped, failed_cases=failed_cases, holdout_pass=holdout["pass"]):
        return finish("failed")

    if patch:
        try:
            def verify_review_input():
                if (engineering.head(root) != base or engineering.evidence(
                        root, base, spec_path, package_path, dependencies, registered=registered) != patch):
                    raise engineering.EngineeringError("the scoped Git evidence changed during the build")
                if any(hand_edits(spec, chosen, root).values()) or content_hash(spec.directory) != spec.sha256:
                    raise engineering.EngineeringError("the spec or generated package changed during the build")

            verify_review_input()
            payload = {"requirement": original, "source": spec.data["factory"].get("source"),
                       "git_base": base, "git_diff": patch,
                       "generated_manifest_diff": engineering.generated_diff(root, base, package_path),
                       "manifest": manifest_for(spec, chosen),
                       "package_sha256": report["package_sha256"], "components": assessment["components"],
                       "dependencies": assessment["dependency_context"], "spec_path": spec_path,
                       "evaluation": {"gates": report["gates"], "executed_cases": [row["id"] for row in rows],
                                      "failed_cases": failed_cases, "holdout": holdout}}
            review_key = engineering.digest(payload)
            review = cached.get("review") if cached.get("review_input_sha256") == review_key else None
            if review is None:
                if not live:
                    raise engineering.EngineeringError("this evaluated package has no matching independent review")
                review = engineering.infer(guard, "review", payload, ledger_root=ledger_root)
                verify_review_input()
            report["engineering"].update(review_input_sha256=review_key, review=review)
            blockers = [row for row in review["result"]["findings"] if row["severity"] == "blocking"]
            if not step("review", not blockers, findings=review["result"]["findings"]):
                return finish("failed")
        except (engineering.EngineeringError, OSError, ValueError) as exc:
            step("review", False, problems=[str(exc)])
            return finish("failed")
        finally:
            report["tokens"] = guard.summary()
    elif prior.get("spec_sha256") == spec.sha256 and prior.get("package_sha256") == report["package_sha256"] and prior.get("engineering"):
        report["engineering"] = prior["engineering"]

    report["supports"] = [state for state in registry.PROMOTION_ORDER[1:]
                          if registry.level_at_least(report["level"], registry.REQUIRED_LEVEL[state]) and holdout["pass"]]
    package_dir = root / PACKAGES_DIR / spec.name
    (package_dir / REPORT_PATH).parent.mkdir(parents=True, exist_ok=True)
    (package_dir / REPORT_PATH).write_text(json.dumps({**report, "status": "candidate"}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    step("report", True, path=(PACKAGES_DIR / spec.name / REPORT_PATH).as_posix())

    try:
        archive = registry.pack(spec.name, root)
    except (registry.RegistryError, PackageError) as exc:
        step("pack", False, problems=[str(exc)])
        return finish("failed")
    report["archive"] = archive
    step("pack", True, **archive)
    if until == "pack":
        return finish("stopped")

    try:
        entry = registry.register(spec.name, root, archive=archive, holdout={"ids": holdout["ids"], "pass": holdout["pass"]},
                                  built={"by": f"factory@{FACTORY_VERSION}", "spec": spec_path, "spec_sha256": spec.sha256,
                                         "candidate": chosen, "work_order": work_order})
    except registry.RegistryError as exc:
        step("register", False, problems=[str(exc)])
        return finish("failed")
    report["registry"] = {"path": registry.REGISTRY_PATH.as_posix(), "state": entry["state"], "level": entry["level"]}
    step("register", True, state=entry["state"])
    return finish("candidate")


def verify(agent_ref: str, root: Path | None = None) -> dict:
    """Does the installed package still match its spec, its evidence, its archive and the registry?"""
    root = repo_root(root)
    name = str(agent_ref).split("@", 1)[0]
    entry = registry.load(root)["agents"].get(name)
    result: dict[str, Any] = {"agent": str(agent_ref), "pass": False, "checks": {}, "problems": []}
    if not entry:
        result["problems"].append("not registered")
        return result
    try:
        package = load_package(agent_ref, root)
    except PackageError as exc:
        result["problems"].append(str(exc))
        return result
    result["agent"] = package.ref
    level = evals.current_level(package.ref, root)
    checks = result["checks"]
    checks["package_matches_registry"] = package.content_sha256 == entry.get("package_sha256")
    checks["evidence_matches_package"] = level["level"] != "none"
    checks["level_matches_registry"] = level["level"] == entry.get("level")
    built = entry.get("built") or {}
    if str(built.get("by", "")).startswith("factory@"):
        try:
            spec = load_spec(name, root)
            checks["spec_matches_registry"] = spec.sha256 == built.get("spec_sha256")
            edits = hand_edits(spec, built.get("candidate") or {}, root)
            checks["no_hand_edits"] = not any(edits.values())
            if not checks["no_hand_edits"]:
                result["hand_edits"] = edits
        except FactoryError as exc:
            checks["spec_matches_registry"] = False
            result["problems"].append(str(exc))
    archive = entry.get("archive") or {}
    path = root / str(archive.get("path") or "")
    if archive.get("path") and path.is_file():
        checks["archive_matches_registry"] = hashlib.sha256(path.read_bytes()).hexdigest() == archive.get("sha256")
    else:
        result["archive"] = "not on disk (archives are build output; re-create with aos-agent pack)"
    result.update(level=level["level"], state=entry.get("state"))
    result["problems"] += [name for name, ok in checks.items() if not ok]
    result["pass"] = not result["problems"]
    return result



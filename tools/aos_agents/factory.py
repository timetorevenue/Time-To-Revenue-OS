REPORT_PATH = "evidence/factory.json"
GENERATED_MARK = "# Generated by the Agent Factory"
PRESERVED_PREFIXES = ("evidence/", "evals/recordings/")   # produced by evaluation, not by the spec
SPEC_TABLES = {"agent", "io", "context", "capabilities", "budget", "compose", "factory"}
BUILDABLE_KINDS = ("tool", "oneshot", "planner")
SAFETY_PROBES = ("canary", "injection", "isolation", "missing_context", "undeclared_effect")
MAX_CANDIDATES = 6
MAX_HOLDOUT_SHARE = 0.4
DEFAULT_HOLDOUT_SHARE = 0.2
SIMILARITY_NOTE_AT = 0.5
QUOTA_ADVISORY_USED_PERCENT = 50.0   # informational only: reported, never blocks
PROVIDER_STOP_CLASSES = ("quota_unavailable", "authentication_unavailable", "needs_authentication")
QUOTA_EXHAUSTED_PERCENT = 100.0       # the provider's own limit: a window at 100% is spent
